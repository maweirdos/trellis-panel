import { randomUUID } from 'node:crypto'
import { resolve } from 'node:path'
import { ipcInvoke, ipcEvent } from '../../shared/ipc-channels'
import { IpcErrorCode, ipcFail } from '../../shared/ipc-errors'
import {
  LEGACY_INTEGRATION_MUTATIONS, legacyIntegrationRequests,
  type LegacyIntegrationOperation, type LegacyIntegrationInput
} from '../../shared/integration-native'
import { handle } from './registry'
import { legacyIntegrationCall } from '../services/daemon-client/integration-legacy'
import { broadcastToWindows } from '../services/bridge'
import { getMainWindow, getProjectRoot, getProjectGeneration } from '../state'
import { DaemonError } from '../daemon/errors'

const canonical = (root: string): string => process.platform === 'win32' ? resolve(root).toLowerCase() : resolve(root)

export function registerIntegrationsIpc(): void {
  // This capability is generated by native code, never accepted from raw input.
  // Recreating a renderer/window gets a new cancellation namespace.
  const owners = new Map<number, string>()
  const reads = new Map<string, AbortController>()
  const authorizations = new Map<string, AbortController>()
  function ownerFor(sender: Electron.WebContents): string {
    const existing = owners.get(sender.id)
    if (existing) return existing
    const owner = randomUUID()
    owners.set(sender.id, owner)
    sender.once('destroyed', () => owners.delete(sender.id))
    return owner
  }
  function cancelDestroyed(ownerId: string, operation: 'cancelRead' | 'cancelAuthorization', requestId: string): void {
    const unavailable = (): void => {
      process.emitWarning('Integration cancellation could not reach the native owner; inspect the original request before retrying.', { code: 'TRELLIS_INTEGRATION_CANCEL_UNAVAILABLE' })
    }
    void legacyIntegrationCall('', operation, { requestId }, ownerId).then(result => { if (!result.ok) unavailable() }, unavailable)
  }
  function register<M extends LegacyIntegrationOperation>(operation: M): void {
    handle(ipcInvoke.integration[operation], async (event, raw: unknown) => {
      const trustedSender = (): boolean => !event.sender.isDestroyed()
        && getMainWindow()?.webContents.id === event.sender.id && event.senderFrame === event.sender.mainFrame
      if (!trustedSender()) return ipcFail(IpcErrorCode.Denied, '集成操作仅允许从原生主窗口发起')
      const parsed = legacyIntegrationRequests[operation].safeParse(operation === 'list' ? {} : raw)
      if (!parsed.success) return ipcFail(IpcErrorCode.InvalidArg, parsed.error.issues[0]?.message || '集成参数无效')
      const ownerId = ownerFor(event.sender)
      const sourceRoot = getProjectRoot(), generation = getProjectGeneration()
      const projectAction = 'expectedRoot' in parsed.data
      const projectSensitive = projectAction || operation === 'list'
      if ('expectedRoot' in parsed.data && (!sourceRoot || canonical(parsed.data.expectedRoot) !== canonical(sourceRoot))) return ipcFail(IpcErrorCode.Conflict, '项目已切换，请在当前项目重新操作')
      // Connection configuration and cancellation are profile operations. Listing
      // additionally uses the actual current project to preserve binding visibility.
      const root = projectSensitive ? sourceRoot ?? '' : ''
      const commandId = randomUUID()
      const input = parsed.data as LegacyIntegrationInput<M>
      const requestId = 'requestId' in parsed.data ? parsed.data.requestId : undefined
      const key = requestId ? `${ownerId}:${requestId}` : ''
      if (operation === 'cancelRead') reads.get(key)?.abort()
      if (operation === 'cancelAuthorization') authorizations.get(key)?.abort()
      const active = operation === 'jiraSearch' ? reads : operation === 'authorize' ? authorizations : undefined
      if (active?.has(key)) return ipcFail(IpcErrorCode.Conflict, '查询或授权标识已在使用')
      if (operation === 'authorize' && authorizations.size) return ipcFail(IpcErrorCode.Conflict, '已有浏览器授权进行中，请完成或取消后重试')
      if (operation === 'jiraSearch' && [...reads.keys()].filter(value => value.startsWith(`${ownerId}:`)).length >= 4) return ipcFail(IpcErrorCode.Denied, '查询数量已达上限，请先等待或取消前一查询')
      const controller = active ? new AbortController() : undefined
      const onDestroyed = (): void => {
        controller?.abort()
        if (requestId && active) cancelDestroyed(ownerId, operation === 'authorize' ? 'cancelAuthorization' : 'cancelRead', requestId)
      }
      if (active && controller) { active.set(key, controller); event.sender.once('destroyed', onDestroyed) }
      const isCurrent = (): boolean => trustedSender() && !controller?.signal.aborted
        && (!projectSensitive || getProjectRoot() === sourceRoot && getProjectGeneration() === generation)
      const mutating = LEGACY_INTEGRATION_MUTATIONS.includes(operation)
      try {
        const result = await legacyIntegrationCall(root, operation, input, ownerId, commandId, isCurrent)
        if (operation === 'inspect' || result.ok && mutating) broadcastToWindows(ipcEvent.integrationsChanged, {})
        if (!isCurrent()) return ipcFail(IpcErrorCode.Conflict, mutating ? '来源项目或请求已改变；后台操作可能已提交，请刷新并检查原结果' : '来源项目或请求已改变，请重新读取当前项目', { commandId, ...(mutating ? { outcome: 'unknown' } : {}) })
        return result
      } catch (error) {
        if (operation === 'inspect') broadcastToWindows(ipcEvent.integrationsChanged, {})
        const code = error instanceof DaemonError ? Object.values(IpcErrorCode).find(value => value === error.code) ?? IpcErrorCode.Upstream : IpcErrorCode.Upstream
        return ipcFail(code, error instanceof DaemonError ? error.message : '集成操作失败，请检查后台连接、网络或本地存储后重试', {
          commandId, ...(error instanceof DaemonError ? { outcome: error.outcome } : {})
        })
      } finally {
        if (active && active.get(key) === controller) active.delete(key)
        if (active && !event.sender.isDestroyed()) event.sender.removeListener('destroyed', onDestroyed)
      }
    })
  }
  register('cancelAuthorization'); register('authorize'); register('cancelRead'); register('list')
  register('saveConnection'); register('removeConnection'); register('inspect'); register('saveBinding'); register('removeBinding')
  register('repositories'); register('pullRequests'); register('links'); register('attach'); register('unlink')
  register('previewNotification'); register('sendNotification'); register('jiraContext'); register('jiraSearch')
  register('jiraTransitions'); register('jiraTransition'); register('jiraComment')
}
