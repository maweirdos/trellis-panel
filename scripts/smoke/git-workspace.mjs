import assert from 'node:assert/strict'
import { existsSync, mkdirSync, readFileSync, renameSync, unlinkSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createGitWorkspaceHarness } from './fixtures/git-workspace-harness.mjs'

const f = await createGitWorkspaceHarness()
const { service, git, repository, status, input, approve } = f
let assertions = 0
const check = (condition, label) => { assert.ok(condition, label); assertions += 1 }
const okay = result => { assert.equal(result.ok, true, JSON.stringify(result)); assertions += 1; return result }
const denied = (result, code) => { assert.equal(result.ok, false, JSON.stringify(result)); if (code) assert.equal(result.code, code, JSON.stringify(result)); assertions += 1; return result }
try {
  const root = repository('working repository')
  const other = repository('other')
  const names = ['first.txt', '空 格.txt', '-option.txt']
  for (const name of names) writeFileSync(join(root, name), 'one\n')
  let snapshot = await status(root)
  check(snapshot.unborn && snapshot.branch === 'main' && snapshot.head === null, 'unborn state is real')
  okay(await service.stage(root, await input(root, { paths: ['空 格.txt', '-option.txt'] })))
  snapshot = await status(root)
  check(snapshot.staged.length === 2 && snapshot.untracked.includes('first.txt'), 'only selected files staged, including Unicode and leading dash')
  const before = readFileSync(join(root, '空 格.txt'))
  okay(await service.unstage(root, await input(root, { paths: ['空 格.txt'] })))
  check(readFileSync(join(root, '空 格.txt')).equals(before), 'unborn unstage preserves worktree bytes')
  okay(await service.stage(root, await input(root, { paths: ['first.txt', '空 格.txt'] })))
  const noReview = await service.commit(root, await input(root, { message: 'first commit' }))
  denied(noReview, 'E_DENIED')
  okay(await service.commit(root, await input(root, { message: 'first 提交' }), approve))
  snapshot = await status(root)
  check(snapshot.clean && snapshot.head && git(root, ['show', '-s', '--format=%s']) === 'first 提交', 'first commit uses approved tree/message')
  check(git(root, ['ls-tree', '-r', '--name-only', 'HEAD']).split('\n').length === 3, 'first tree contains exact staged paths')

  writeFileSync(join(root, 'first.txt'), 'two\n')
  writeFileSync(join(root, 'unrelated.txt'), 'not selected\n')
  const stale = await input(root, { paths: ['first.txt'] })
  writeFileSync(join(root, 'first.txt'), 'three\n')
  denied(await service.stage(root, stale), 'E_CONFLICT')
  okay(await service.stage(root, await input(root, { paths: ['first.txt'] })))
  snapshot = await status(root)
  check(snapshot.staged.length === 1 && snapshot.untracked.includes('unrelated.txt'), 'unrelated unstaged/untracked content is preserved')
  const original = readFileSync(join(root, 'first.txt'))
  okay(await service.unstage(root, await input(root, { paths: ['first.txt'] })))
  check(readFileSync(join(root, 'first.txt')).equals(original), 'tracked unstage preserves worktree bytes')
  okay(await service.stage(root, await input(root, { paths: ['first.txt'] })))
  okay(await service.commit(root, await input(root, { message: 'second' }), approve))
  check(git(root, ['show', 'HEAD:first.txt']) === 'three', 'second commit has new content')
  check((await status(root)).untracked.includes('unrelated.txt'), 'commit leaves unrelated worktree file')

  const old = git(root, ['rev-parse', 'HEAD'])
  writeFileSync(join(root, 'first.txt'), 'four\n')
  okay(await service.stage(root, await input(root, { paths: ['first.txt'] })))
  const reviewed = await input(root, { message: 'concurrent review' })
  denied(await service.commit(root, reviewed, { review: async () => { git(root, ['add', '--', 'unrelated.txt']); return true } }), 'E_CONFLICT')
  check(git(root, ['rev-parse', 'HEAD']) === old, 'concurrent staging after review creates no commit')
  check(git(root, ['diff', '--cached', '--name-only']).includes('unrelated.txt'), 'concurrent staging is never removed or included silently')
  okay(await service.unstage(root, await input(root, { paths: ['unrelated.txt'] })))
  okay(await service.commit(root, await input(root, { message: 'reviewed only' }), approve))
  check(!git(root, ['show', '--pretty=', '--name-only', 'HEAD']).includes('unrelated.txt'), 'commit excludes unreviewed file')
  unlinkSync(join(root, 'unrelated.txt'))

  renameSync(join(root, '空 格.txt'), join(root, 'renamed 名.txt'))
  okay(await service.stage(root, await input(root, { paths: ['空 格.txt', 'renamed 名.txt'] })))
  snapshot = await status(root)
  check(snapshot.staged.some(change => change.origPath === '空 格.txt' && change.path === 'renamed 名.txt'), 'rename source/destination recognized')
  okay(await service.unstage(root, await input(root, { paths: ['renamed 名.txt'] })))
  check(existsSync(join(root, 'renamed 名.txt')) && !existsSync(join(root, '空 格.txt')), 'rename unstage keeps working rename')
  okay(await service.stage(root, await input(root, { paths: ['空 格.txt', 'renamed 名.txt'] })))
  okay(await service.commit(root, await input(root, { message: 'rename' }), approve))
  unlinkSync(join(root, 'first.txt'))
  okay(await service.stage(root, await input(root, { paths: ['first.txt'] })))
  check((await status(root)).staged.some(change => change.path === 'first.txt' && change.x === 'D'), 'deleted file staged')
  okay(await service.unstage(root, await input(root, { paths: ['first.txt'] })))
  check(!existsSync(join(root, 'first.txt')), 'unstage deletion does not restore worktree file')
  okay(await service.stage(root, await input(root, { paths: ['first.txt'] })))
  okay(await service.commit(root, await input(root, { message: 'delete' }), approve))

  for (const path of ['../outside', '/outside', 'C:\\outside', '.git/config', 'folder/../first.txt']) denied(await service.stage(root, await input(root, { paths: [path] })), 'E_INVALID_ARG')
  denied(await service.stage(root, { ...await input(root, { paths: ['-option.txt'] }), expectedRoot: other }), 'E_CONFLICT')
  denied(await service.stage(root, { ...await input(root, { paths: ['-option.txt'] }), confirm: false }), 'E_INVALID_ARG')
  denied(await service.commit(root, await input(root, { message: '' }), approve), 'E_INVALID_ARG')
  denied(await service.commit(root, await input(root, { message: 'empty index' }), approve), 'E_INVALID_ARG')

  okay(await service.createBranch(root, await input(root, { name: 'feature/ui', switchAfter: true })))
  check((await status(root)).branch === 'feature/ui', 'create and switch local branch')
  writeFileSync(join(root, 'dirty.txt'), 'dirty\n')
  denied(await service.switchBranch(root, await input(root, { name: 'main' })), 'E_CONFLICT')
  check(readFileSync(join(root, 'dirty.txt'), 'utf8') === 'dirty\n' && (await status(root)).branch === 'feature/ui', 'dirty switch refuses without discarding bytes')
  denied(await service.createBranch(root, await input(root, { name: '--force' })), 'E_INVALID_ARG')
  denied(await service.createBranch(root, await input(root, { name: 'feature/ui' })), 'E_CONFLICT')
  unlinkSync(join(root, 'dirty.txt'))
  okay(await service.switchBranch(root, await input(root, { name: 'main' })))
  check((await status(root)).branch === 'main', 'clean switch succeeds')

  const bare = repository('remote.git', true)
  git(root, ['remote', 'add', 'origin', bare])
  denied(await service.push(root, await input(root, { remote: 'origin', branch: 'main', remoteBranch: 'main' })), 'E_DENIED')
  okay(await service.push(root, await input(root, { remote: 'origin', branch: 'main', remoteBranch: 'main', setUpstream: true }), approve))
  check(git(bare, ['rev-parse', 'refs/heads/main']) === git(root, ['rev-parse', 'HEAD']), 'normal push reaches disposable bare remote')
  check(git(root, ['config', '--get', 'branch.main.remote']) === 'origin' && git(root, ['config', '--get', 'branch.main.merge']) === 'refs/heads/main', 'explicit upstream configured')
  denied(await service.push(root, await input(root, { remote: 'missing', branch: 'main', remoteBranch: 'main' }), approve), 'E_NOT_FOUND')
  denied(await service.push(root, await input(root, { remote: 'origin', branch: 'main', remoteBranch: 'main:other' }), approve), 'E_INVALID_ARG')

  const linked = join(f.directory, 'linked')
  git(root, ['worktree', 'add', '-q', linked, 'feature/ui'])
  check((await status(linked)).branch === 'feature/ui', 'linked worktree .git file is recognized')
  denied(await service.switchBranch(root, await input(root, { name: 'feature/ui' })))
  check((await status(root)).branch === 'main', 'in-use worktree branch is not forced')
  const staleBranch = await input(root, { name: 'feature/ui' })
  git(root, ['branch', 'new-local'])
  denied(await service.switchBranch(root, staleBranch), 'E_CONFLICT')
  denied(await service.createBranch(root, await input(root, { name: 'guarded' }), { guard: () => false }), 'E_CONFLICT')
  check(!(await status(root)).branches.some(branch => branch.name === 'guarded'), 'queue guard blocks obsolete action')
  console.log(`GIT_WORKSPACE_PASSED (${assertions} assertions; actual disposable repositories, selected index operations, exact reviewed commits, branches/worktrees and local bare push)`)
} finally { f.close() }
