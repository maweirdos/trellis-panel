import assert from 'node:assert/strict'
import { existsSync, mkdirSync, renameSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { database } from './task-conversations-data.mjs'

export async function exercise(Service, f) {
  let service = new Service(f.options)
  try {
  let checks = 0
  const check = (condition, message) => { assert.ok(condition, message); checks++ }
  const rejected = async (run, code) => { await assert.rejects(run, error => error.code === code); checks++ }
  const initialDigest = f.digest()
  let candidates = await service.discover(f.root)
  check(candidates.items.length === 4, 'only valid current-project IDs from all three actual schemas: ' + JSON.stringify(candidates.sources) + ' ' + candidates.items.map(item => item.source + ':' + item.sessionId).join(','))
  check(candidates.sources.every(source => source.available), 'source metadata available independently')
  check(!candidates.items.some(item => /Foreign|Deleted|technical/.test(item.title)), 'foreign/deleted/invalid IDs filtered')
  check(candidates.items.find(item => item.source === 'zcode').sessionId === f.zcodeId, 'ZCode uses task_id, never ACP ID')
  check(candidates.items.find(item => item.source === 'zcode').capability === 'workspace', 'ZCode never claims session routing')
  check(candidates.items.find(item => item.source === 'claude-code').destinationLabel === '终端续接', 'Claude actual destination explicit')
  check(candidates.items.find(item => item.source === 'claude-code').title === 'Named Claude session', 'Claude reads native custom title')
  const first = candidates.items.find(item => item.sessionId === f.codexId)
  let snapshot = await service.bind(f.root, 'task-a', first.id)
  check(snapshot.bindings.length === 1 && snapshot.bindings[0].primary, 'first manual association is primary')
  let binding = snapshot.bindings[0]
  check(binding.taskRef === 'task:stable-task-a', 'uses taskRefFor stable identity')
  assert.deepEqual(f.digest(), initialDigest, 'reads, binding and persistence do not mutate native sources'); checks++
  database(f.codexFile, null, db => db.prepare('UPDATE threads SET name=?,updated_at_ms=? WHERE id=?').run('Renamed native thread', 1800000000456, f.codexId))
  snapshot = await service.list(f.root)
  check(snapshot.bindings[0].conversation.title === 'Renamed native thread' && snapshot.bindings[0].id === binding.id, 'native rename refreshes title without losing stable binding')
  check(snapshot.bindings[0].conversation.updatedAt === 1800000000456, 'native milliseconds preserved')
  f.runtimeRecord(`${f.codexOther}.json`, { platform: 'session', current_task: '.trellis/tasks/task-a', last_seen_at: '2001-01-01T00:00:00Z' })
  f.runtimeRecord('unverified.json', { platform: 'codex', session_id: 'guessed-title', current_task: '.trellis/tasks/task-a' })
  f.runtimeRecord('no-task.json', { platform: 'codex', session_id: f.codexOther })
  snapshot = await service.list(f.root)
  check(snapshot.bindings.length === 2, 'runtime imports only verified native ID and explicit current_task')
  check(snapshot.bindings.find(item => item.id === binding.id).primary, 'automatic runtime import preserves manual primary')
  check(snapshot.bindings.some(item => item.origin === 'runtime' && item.conversation.sessionId === f.codexOther), 'legacy filename is validated against native metadata')
  const runtimeBinding = snapshot.bindings.find(item => item.origin === 'runtime')
  await service.setPrimary(f.root, 'task-a', runtimeBinding.id)
  snapshot = await service.list(f.root)
  check(snapshot.bindings.find(item => item.id === runtimeBinding.id).primary, 'explicit primary survives repeated automatic import')
  await service.setPrimary(f.root, 'task-a', binding.id)
  await service.unbind(f.root, 'task-a', runtimeBinding.id)
  check((await service.list(f.root)).bindings.length === 1, 'explicit unlink suppresses automatic reimport')
  await service.bind(f.root, 'task-a', candidates.items.find(item => item.source === 'claude-code').id)
  await service.setPrimary(f.root, 'task-a', binding.id)
  renameSync(f.runtime, join(f.base, 'removed-runtime'))
  check(!existsSync(f.runtime), 'all runtime records removed from the project before restart')
  service.close()
  service = new Service(f.options)
  snapshot = await service.list(f.root)
  check(snapshot.bindings.length === 2 && snapshot.bindings.find(item => item.id === binding.id).primary, 'bindings and primary persist across restart and runtime removal')
  check(!existsSync(join(f.root, '.trellis', '.panel', 'runtime', 'observations.sqlite')), 'works without observability and never creates observations.sqlite')
  await service.open(f.root, 'task-a', binding.id)
  assert.deepEqual(f.calls.pop(), { kind: 'protocol', source: 'codex', url: `codex://threads/${f.codexId}`, cwd: f.root }); checks++
  f.capabilities.set('codex', { available: true, packageFamilyName: 'OpenAI.Codex_2p2nqsd0c76g0' })
  await service.open(f.root, 'task-a', binding.id)
  assert.deepEqual(f.calls.pop(), { kind: 'packaged-protocol', source: 'codex', url: `codex://threads/${f.codexId}`, cwd: f.root, packageFamilyName: 'OpenAI.Codex_2p2nqsd0c76g0' }); checks++
  f.capabilities.clear()
  const claudeBinding = snapshot.bindings.find(item => item.conversation.source === 'claude-code')
  const opened = await service.open(f.root, 'task-a', claudeBinding.id)
  assert.deepEqual(f.calls.pop(), { kind: 'terminal', source: 'claude-code', executable: join(f.base, 'native', 'claude.exe'), args: ['--resume', f.claudeId], cwd: f.root }); checks++
  check(opened.destinationLabel === '终端续接' && opened.capability === 'session', 'terminal restoration never claims original-window focus')
  await rejected(() => service.open(f.root, 'task-b', binding.id), 'E_NOT_FOUND')
  await rejected(() => service.open(f.root, '../task-a', binding.id), 'E_INVALID_ARG')
  await rejected(() => service.bind(f.root, 'task-a', 'codex://threads/new'), 'E_NOT_FOUND')
  let current = true
  f.setOnCapability(async () => { current = false })
  await rejected(() => service.open(f.root, 'task-a', binding.id, () => current), 'E_CONFLICT')
  check(f.calls.length === 0, 'root/generation owner guard runs after asynchronous preflight')
  f.setOnCapability(undefined)
  f.capabilities.set('codex', { available: false, detail: 'protocol removed' })
  snapshot = await service.list(f.root)
  check(snapshot.bindings.find(item => item.id === binding.id).conversation.unavailableReason === 'protocol removed', 'missing protocol retains cached association and visible reason')
  await rejected(() => service.open(f.root, 'task-a', binding.id), 'E_UNAVAILABLE')
  f.capabilities.clear()
  const zcode = candidates.items.find(item => item.source === 'zcode')
  await service.bind(f.root, 'task-b', candidates.items.find(item => item.source === 'claude-code').id)
  snapshot = await service.bind(f.root, 'task-b', zcode.id)
  const zBinding = snapshot.bindings.find(item => item.conversation.source === 'zcode')
  check((await service.open(f.root, 'task-b', zBinding.id)).capability === 'workspace', 'open result carries verified workspace capability')
  const zTarget = f.calls.pop()
  check(zTarget.url.startsWith('zcode://workspace/open?') && new URL(zTarget.url).searchParams.get('path') === f.root && !zTarget.url.includes(f.zcodeId), 'ZCode URL encodes exact cwd without invented session routing')
  database(f.zcodeFile, 'ALTER TABLE tasks RENAME TO unsupported_tasks')
  snapshot = await service.list(f.root)
  check(!snapshot.sources.find(item => item.source === 'zcode').available && snapshot.sources.find(item => item.source === 'codex').available, 'unsupported schema isolated from other sources')
  check(snapshot.bindings.find(item => item.id === zBinding.id).conversation.title === 'Real ZCode task title', 'unavailable source retains cached native title')
  database(f.zcodeFile, 'ALTER TABLE unsupported_tasks RENAME TO tasks')
  const archive = join(f.root, '.trellis', 'tasks', 'archive', '2026-10', 'task-a')
  mkdirSync(dirname(archive), { recursive: true })
  renameSync(join(f.root, '.trellis', 'tasks', 'task-a'), archive)
  snapshot = await service.list(f.root)
  check(snapshot.bindings.find(item => item.id === binding.id).taskDir === 'archive/2026-10/task-a', 'only unique same-ID archive move continues old binding')
  await service.open(f.root, 'archive/2026-10/task-a', binding.id); f.calls.pop()
  f.task('copy-a', 'stable-task-a')
  snapshot = await service.list(f.root)
  check(!snapshot.bindings.some(item => item.taskDir === 'copy-a'), 'duplicate task ID never acquires original associations')
  await rejected(() => service.open(f.root, 'copy-a', binding.id), 'E_NOT_FOUND')
  f.task('copy-b', 'stable-task-a')
  renameSync(archive, join(f.base, 'removed-task'))
  check(!existsSync(archive), 'archived fixture removed before alias resolution')
  snapshot = await service.list(f.root)
  check(snapshot.bindings.find(item => item.id === binding.id).conversation.capability === 'unavailable', 'multiple same-ID archive candidates remain unresolved')
  database(f.codexFile, null, db => db.prepare('DELETE FROM threads WHERE id=?').run(f.codexOther))
  await rejected(() => service.bind(f.root, 'task-b', candidates.items.find(item => item.sessionId === f.codexOther).id), 'E_NOT_FOUND')
  // Recheck native existence after an asynchronous capability change, before any launch.
  const taskBClaude = snapshot.bindings.find(item => item.taskDir === 'task-b' && item.conversation.source === 'claude-code')
  f.setOnCapability(async source => { if (source === 'claude-code' && existsSync(f.claudeFile)) renameSync(f.claudeFile, join(f.base, 'removed-claude.jsonl')) })
  await rejected(() => service.open(f.root, 'task-b', taskBClaude.id), 'E_NOT_FOUND')
  f.setOnCapability(undefined)
  service.close()
  return checks
  } finally { service.close() }
}
